type testAPI struct {
	t                    *testing.T
	store                *store
	public, admin, token string
}

func newTestAPI(t *testing.T) testAPI {
	t.Helper()
	s, err := openStore(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { s.db.Close() })
	var key [32]byte
	rand.Read(key[:])
	token := hex.EncodeToString(key[:])
	public := httptest.NewServer(s.publicHandler())
	admin := httptest.NewServer(s.adminHandler(token))
	t.Cleanup(admin.Close)
	t.Cleanup(public.Close)
	return testAPI{t, s, public.URL, admin.URL, token}
}

func (api testAPI) request(method, base, path, token, media string, body []byte, want int) ([]byte, http.Header) {
	api.t.Helper()
	req, err := http.NewRequest(method, base+path, bytes.NewReader(body))
	if err != nil {
		api.t.Fatal(err)
	}
	if token != "" {
		req.Header.Set("Authorization", "Bearer "+token)
	}
	if media != "" {
		req.Header.Set("Content-Type", media)
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		api.t.Fatal(err)
	}
	defer resp.Body.Close()
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		api.t.Fatal(err)
	}
	if resp.StatusCode != want {
		api.t.Fatalf("%s %s returned %d, wanted %d: %s", method, path, resp.StatusCode, want, data)
	}
	return data, resp.Header
}

func (api testAPI) get(path string, status int) []byte {
	api.t.Helper()
	body, _ := api.request("GET", api.public, path, "", "", nil, status)
	return body
}

func (api testAPI) put(path, body string, status int) {
	api.t.Helper()
	api.request("PUT", api.admin, adminPrefix+path, api.token, "application/json", []byte(body), status)
}

func parse[T any](t *testing.T, body []byte) T {
	t.Helper()
	var data T
	if err := json.Unmarshal(body, &data); err != nil {
		t.Fatalf("invalid JSON: %v", err)
	}
	return data
}

type testModsPage struct {
	Mods []mod `json:"mods"`
	Next *int  `json:"next_offset"`
}

type testGamesPage struct {
	Games []game `json:"games"`
	Next  *int   `json:"next_offset"`
}

func approved(t *testing.T, v version, bytes []byte) {
	t.Helper()
	digest := sha256.Sum256(bytes)
	if int64(len(bytes)) != v.SizeBytes || hex.EncodeToString(digest[:]) != v.SHA256 {
		t.Fatal("download disagrees with published size or digest")
	}
}

func TestDemoCatalogAndDownload(t *testing.T) {
	api := newTestAPI(t)
	api.get("/healthz", 200)
	if err := api.store.seedDemo(context.Background()); err != nil {
		t.Fatal(err)
	}
	if err := api.store.seedDemo(context.Background()); err != nil {
		t.Fatal(err)
	}
	first := parse[testGamesPage](t, api.get("/api/v1/games?limit=2", 200))
	if len(first.Games) != 2 || first.Next == nil || *first.Next != 2 {
		t.Fatalf("unexpected first page: %#v", first)
	}
	last := parse[testGamesPage](t, api.get("/api/v1/games?limit=2&offset=2", 200))
	if len(last.Games) != 1 || last.Next != nil || last.Games[0].ModCount != 2 {
		t.Fatalf("unexpected last page: %#v", last)
	}
	list := parse[testModsPage](t, api.get("/api/v1/mods?title_id=0400c3f00006e000&q=LANGUAGE&type=translation&sort=name", 200))
	if len(list.Mods) != 1 || list.Mods[0].ID != "demo-kart-translation" || !list.Mods[0].Demo {
		t.Fatalf("unexpected filtered mods: %#v", list.Mods)
	}
	m := parse[modDetail](t, api.get("/api/v1/mods/"+list.Mods[0].ID, 200))
	if len(m.Versions) != 1 || !reflect.DeepEqual(m.TitleIDs, []string{"0400C3F00006E000"}) ||
		m.Versions[0].GameVersion != demoGameVersion || m.Versions[0].BuildID != demoBuildID ||
		m.Versions[0].MinLichiiBuild != "build-1" || m.Status != "" {
		t.Fatalf("unexpected demo detail: %#v", m)
	}
	imageData, h := api.request("GET", api.public, *m.PreviewURL, "", "", nil, 200)
	img, detected, err := image.DecodeConfig(bytes.NewReader(imageData))
	if err != nil || detected != "png" || img.Width != 640 || img.Height != 360 || h.Get("Content-Type") != "image/png" {
		t.Fatal("demo preview is not the generated PNG")
	}
	v := m.Versions[0]
	body, h := api.request("GET", api.public, v.DownloadURL, "", "", nil, 200)
	approved(t, v, body)
	if h.Get("Content-Type") != "application/zip" || h.Get("Cache-Control") != "no-store" {
		t.Fatalf("unexpected download headers: %v", h)
	}
	var regenerated bytes.Buffer
	size, err := writeDemoZIP(&regenerated, m.ID)
	if err != nil || size != v.UnpackedSizeBytes || !bytes.Equal(body, regenerated.Bytes()) {
		t.Fatal("demo archive is not deterministic or disagrees with its unpacked size")
	}
	z, err := zip.NewReader(bytes.NewReader(body), int64(len(body)))
	if err != nil || len(z.File) != 2 {
		t.Fatal("demo ZIP must contain exactly two files")
	}
	install := filepath.Join(t.TempDir(), "load", v.TitleID, m.ID)
	for i, name := range []string{"README.txt", "romfs/lichii-modstore-" + m.ID + "-marker.txt"} {
		f := z.File[i]
		if f.Name != name || !f.Mode().IsRegular() {
			t.Fatalf("unexpected fixture entry %q", f.Name)
		}
		r, err := f.Open()
		if err != nil {
			t.Fatal(err)
		}
		content, err := io.ReadAll(r)
		r.Close()
		if err != nil {
			t.Fatal(err)
		}
		dst := filepath.Join(install, name)
		if err := os.MkdirAll(filepath.Dir(dst), 0700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(dst, content, 0600); err != nil {
			t.Fatal(err)
		}
	}
	marker, err := os.ReadFile(filepath.Join(install, "romfs", "lichii-modstore-"+m.ID+"-marker.txt"))
	if err != nil || string(marker) != "Inert Lichii Mod Store test marker.\n" {
		t.Fatal("demo marker did not install at the expected fixture path")
	}
	api.put("/mods/"+m.ID+"/status", `{"status":"rejected"}`, 204)
	if err := api.store.seedDemo(context.Background()); err != nil {
		t.Fatal(err)
	}
	api.get(v.DownloadURL, 404)
}

func TestPrivateModerationAndMultipleTargets(t *testing.T) {
	api := newTestAPI(t)
	const id = "test-testcard"
	path := "/mods/" + id
	const metadata = `{"name":"Test Card","summary":"A test card","description":"Local fixture.","author":"Example","type":"fps"}`
	api.request("PUT", api.public, adminPrefix+path, api.token, "application/json", []byte(metadata), 404)
	api.request("PUT", api.admin, adminPrefix+path, "", "application/json", []byte(metadata), 401)
	api.request("PUT", api.admin, adminPrefix+path, "invalid", "application/json", []byte(metadata), 401)
	api.put("/games/040074a01bf12000", `{"name":"Fixture A"}`, 204)
	api.put("/games/040077201be50000", `{"name":"Fixture B"}`, 204)
	api.put(path, metadata, 204)
	api.get(publicPrefix+path, 404)
	api.get(publicPrefix+path+"/preview", 404)

	var preview bytes.Buffer
	if err := writeDemoPreview(&preview, demos[0].tint); err != nil {
		t.Fatal(err)
	}
	api.request("PUT", api.admin, adminPrefix+path+"/preview", api.token, "image/png", preview.Bytes(), 204)
	privatePreview, _ := api.request("GET", api.admin, adminPrefix+path+"/preview", api.token, "", nil, 200)
	if !bytes.Equal(privatePreview, preview.Bytes()) {
		t.Fatal("review preview differs from the original upload")
	}

	var zipBody bytes.Buffer
	if _, err := writeDemoZIP(&zipBody, id); err != nil {
		t.Fatal(err)
	}
	q := url.Values{"title_id": {"040074a01bf12000"}, "game_version": {"1.0.2"}, "build_id": {strings.Repeat("ab", 32)},
		"min_lichii_build": {"build-401"}}
	oneURL := adminPrefix + path + "/versions/1.0.0?" + q.Encode()
	api.request("PUT", api.admin, oneURL, api.token, "application/zip", []byte("not a ZIP"), 400)
	oneBody, _ := api.request("PUT", api.admin, oneURL, api.token, "application/zip", zipBody.Bytes(), 201)
	one := parse[version](t, oneBody)
	if one.Status != "pending" || one.BuildID != strings.ToUpper(q.Get("build_id")) ||
		one.GameVersion != "1.0.2" || one.MinLichiiBuild != "build-401" || one.TitleID != "040074A01BF12000" {
		t.Fatalf("unexpected uploaded compatibility: %#v", one)
	}
	api.request("PUT", api.admin, oneURL, api.token, "application/zip", zipBody.Bytes(), 409)
	review, _ := api.request("GET", api.admin, one.DownloadURL, api.token, "", nil, 200)
	approved(t, one, review)
	api.put(path+"/status", `{"status":"approved"}`, 204)
	api.get(publicPrefix+path, 404)
	api.put(path+"/versions/1.0.0/status", `{"status":"approved"}`, 204)
	q.Set("title_id", "040077201be50000")
	q.Set("min_lichii_build", "build-0")
	twoURL := adminPrefix + path + "/versions/1.0.0-b?"
	api.request("PUT", api.admin, twoURL+q.Encode(), api.token, "application/zip", zipBody.Bytes(), 400)
	q.Set("min_lichii_build", "build-10")
	twoBody, _ := api.request("PUT", api.admin, twoURL+q.Encode(), api.token, "application/zip", zipBody.Bytes(), 201)
	two := parse[version](t, twoBody)
	if one.SHA256 != two.SHA256 {
		t.Fatal("the same normalized ZIP should be reusable across targets")
	}
	if d := parse[modDetail](t, api.get(publicPrefix+path, 200)); len(d.Versions) != 1 || len(d.TitleIDs) != 1 || d.Versions[0].Status != "" {
		t.Fatalf("pending target leaked into public detail: %#v", d)
	}
	api.get(strings.Replace(two.DownloadURL, adminPrefix, publicPrefix, 1), 404)
	filter := publicPrefix + "/mods?title_id=040077201BE50000"
	if page := parse[testModsPage](t, api.get(filter, 200)); page.Mods == nil || len(page.Mods) != 0 {
		t.Fatal("pending target must not match a public filter")
	}
	api.put(path+"/versions/1.0.0-b/status", `{"status":"approved"}`, 204)
	page := parse[testModsPage](t, api.get(filter, 200))
	if len(page.Mods) != 1 || !reflect.DeepEqual(page.Mods[0].TitleIDs, []string{"040074A01BF12000", "040077201BE50000"}) {
		t.Fatalf("approved target did not enter the public list: %#v", page.Mods)
	}
	publicPreview := api.get(*page.Mods[0].PreviewURL, 200)
	if !bytes.Equal(publicPreview, preview.Bytes()) {
		t.Fatal("public preview differs from the original upload")
	}
	detail := parse[modDetail](t, api.get(publicPrefix+path, 200))
	if len(detail.Versions) != 2 {
		t.Fatalf("unexpected approved versions: %#v", detail.Versions)
	}
	for _, v := range detail.Versions {
		approved(t, v, api.get(v.DownloadURL, 200))
	}
	api.put(path, metadata, 204)
	api.get(publicPrefix+path, 200)
	api.put(path, strings.Replace(metadata, "Test Card", "Revised Test Card", 1), 204)
	api.get(publicPrefix+path, 404)
	api.get(*page.Mods[0].PreviewURL, 404)
}

func TestInvalidRequests(t *testing.T) {
	api := newTestAPI(t)
	for _, query := range []string{"limit=0", "offset=-1", "type=unknown", "q=first&q=second", "sort=unknown", "title_id=1"} {
		err := api.get(publicPrefix+"/mods?"+query, 400)
		if !bytes.Contains(err, []byte(`"code":"invalid_input"`)) {
			t.Fatalf("no useful JSON error for %s", query)
		}
	}
	path := "/mods/fixture"
	api.put(path, strings.Repeat("a", (24<<10)+1), 413)
	api.put(path, "{}", 400)
	api.put(path, `{"name":"Fixture","summary":"Test","description":"Safe","author":"Test","type":"fps"}`, 204)
	api.request("PUT", api.admin, adminPrefix+path+"/preview", api.token, "image/png", []byte("not an image"), 400)
	api.request("PUT", api.admin, adminPrefix+path+"/preview", api.token, "image/png", make([]byte, maxPreviewBytes+1), 413)
	api.request("PUT", api.admin, adminPrefix+path+"/preview", api.token, "image/svg+xml", nil, 415)
}

func TestArchiveNames(t *testing.T) {
	for _, name := range []string{"romfs", "File 01.txt", "1.0.0-demo"} {
		if !portableName(name) {
			t.Errorf("rejected portable name %q", name)
		}
	}
	for _, name := range []string{".", "..", "COM1", "aux.txt", "file ", "file.", "file:name", "file\x00name"} {
		if portableName(name) {
			t.Errorf("accepted nonportable name %q", name)
		}
	}
	for _, tc := range []struct {
		files []string
		want  error
	}{
		{[]string{"romfs/Card.txt", "romfs/card.txt"}, errInvalidZIP},
		{[]string{"README.txt"}, errInvalidZIP},
		{[]string{"romfs/", "README.txt"}, errInvalidZIP},
		{[]string{"ROMFS/Card.txt"}, errInvalidZIP},
		{[]string{"custom/Card.txt"}, errInvalidZIP},
		{[]string{"romfs_ext/Card.txt", "README.txt", "LICENSE.md"}, nil},
		{[]string{"romfslite/Card.txt"}, nil},
		{[]string{"exefs/Card.txt"}, nil},
		{[]string{"cheats/Card.txt"}, nil},
	} {
		var buf bytes.Buffer
		z := zip.NewWriter(&buf)
		for _, name := range tc.files {
			dst, err := z.Create(name)
			if err != nil {
				t.Fatal(err)
			}
			if !strings.HasSuffix(name, "/") {
				if _, err := io.WriteString(dst, "inert text"); err != nil {
					t.Fatal(err)
				}
			}
		}
		if err := z.Close(); err != nil {
			t.Fatal(err)
		}
		if _, err := normalizeZIP(bytes.NewReader(buf.Bytes()), int64(buf.Len()), io.Discard); err != tc.want {
			t.Errorf("archive with %v returned %v, want %v", tc.files, err, tc.want)
		}
	}
}
